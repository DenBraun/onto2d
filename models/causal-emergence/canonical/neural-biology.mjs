  const selected = evidence[key];
  const claimId = `D-cog-${slug}-scope`, boundaryClaimId = `D-cog-${slug}-assay-boundary`;
  const scopeNodeId = `cog:${slug}`, boundaryNodeId = `cog:${slug}-assay-boundary`;
